/**
 * Wheelyx Frontend — Config Sync Utility
 * Reads .env file and syncs VITE_API_BASE_URL / API_BASE_URL into assets/js/config.js.
 * Run with: node build-config.js (or npm run build)
 */

const fs = require('fs');
const path = require('path');

const envPath = path.join(__dirname, '.env');
const configJsPath = path.join(__dirname, 'src', 'main', 'webapp', 'assets', 'js', 'config.js');

let apiUrl = '';

if (fs.existsSync(envPath)) {
    const envContent = fs.readFileSync(envPath, 'utf8');
    const lines = envContent.split(/\r?\n/);
    for (const line of lines) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith('#')) continue;
        const eqIdx = trimmed.indexOf('=');
        if (eqIdx > 0) {
            const key = trimmed.substring(0, eqIdx).trim();
            const val = trimmed.substring(eqIdx + 1).trim().replace(/^['"]|['"]$/g, '');
            if (key === 'VITE_API_BASE_URL' || key === 'API_BASE_URL' || key === 'BACKEND_URL') {
                if (val) {
                    apiUrl = val;
                }
            }
        }
    }
}

// Environment variables take precedence (e.g. in CI/CD)
if (process.env.VITE_API_BASE_URL) {
    apiUrl = process.env.VITE_API_BASE_URL;
} else if (process.env.API_BASE_URL) {
    apiUrl = process.env.API_BASE_URL;
}

const configContent = `/**
 * Wheelyx Frontend — Runtime API & Environment Configuration
 * Auto-generated by build-config.js (or manually edited)
 */
window.WHEELYX_CONFIG = window.WHEELYX_CONFIG || {
    API_BASE_URL: '${apiUrl}'
};

window.getWheelyxApiUrl = function (path) {
    const config = window.WHEELYX_CONFIG || {};
    let baseUrl = config.API_BASE_URL || window.VITE_API_BASE_URL || window.WHEELYX_API_BASE_URL || '';

    if (!baseUrl) {
        baseUrl = window.WHEELYX_CONTEXT_PATH || '';
    }

    if (baseUrl.endsWith('/')) {
        baseUrl = baseUrl.slice(0, -1);
    }

    if (!path.startsWith('/')) {
        path = '/' + path;
    }

    return baseUrl + path;
};
`;

fs.writeFileSync(configJsPath, configContent, 'utf8');
console.log(`[Wheelyx Frontend] Config synced successfully. API_BASE_URL: "${apiUrl || '(empty - defaulting to local context path)'}"`);
